# Q6: Simple Calculator
# Write a program that:
# Takes two numbers as input from the user.
# Prints their sum, difference, product, and quotient.


# Prompting for input from the user for first number:
num_1 = int(input("Please enter the first number : \t"))

#Prompting for input from the user for second number:
num_2 = int(input("Please enter the second number :\t"))

print("Sum of",num_1,"and",num_2,"is equal to",num_1+num_2)
print("Difference of",num_1,"and",num_2,"is equal to",num_1-num_2)
print("Product of",num_1,"and",num_2,"is equal to",num_1*num_2)
print("Quotient of",num_1,"and",num_2,"is equal to",num_1/num_2)