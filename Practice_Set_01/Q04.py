# Q4: Typecasting Practice
# You are given a string:
# num = "45"
# Convert it into an integer and add 10 to it. Print the result.

#Given String
num = "45"

#Type casting the string to integer!

new_num = int(num)

#Printing the value of the variable post casting it to integer and adding 10 to it.
print("The addition of given string value",new_num,"+ 10 =",new_num+10)